const CAT_ART = { malt:'kernel', hop:'cone', yeast:'flask', adjunct:'sugar', process:'clipboard', token:'bug' };

function cardArtSpec(c) {
  const id = c.id;
  let [shape, base, accent] = CARD_ART[id] || [];
  shape = shape || CAT_ART[c.cat] || 'clipboard';
  if (!base) {
    if (c.cat === 'malt') base = MALT_TINT[id] || (/^crystal\d+$/.test(id) ? crystalTint(id) : '#e6c060');
    else if (c.cat === 'hop') {
      // noble hops keep the classic soft green, tipped with their other flavor
      const tags = (c.tags || []).includes('noble') ? { ...c, tags: ['noble', ...c.tags.filter(t => t !== 'noble')] } : c;
      base = firstTagTint(tags, TAG_TINT) || '#7cb342'; accent = accent || firstTagTint(tags, TAG_TINT, 1);
    }
    else if (c.cat === 'yeast') { base = firstTagTint(c, YEAST_TAG_TINT) || '#e9d29a'; accent = accent || '#fff6dc'; }
    else if (shape === 'mug') base = '#ffc93c';
    else base = firstTagTint(c, TAG_TINT) || '#b0bec5';
  }
  return { shape, base, accent };
}

const _artCache = {};
function spriteSvg(shape, base, accent, opts = {}) {
  const key = [shape, base, accent, opts.rare, opts.legendary].join('|');
  if (_artCache[key]) return _artCache[key];
  const grid = SPRITES[shape] || SPRITES.clipboard;
  const pal = { ...SPRITE_FIXED,
    o: opts.legendary ? '#ffc93c' : shadeHex(base, -0.72), c: shadeHex(base, -0.32), a: base,
    b: shadeHex(base, 0.32), w: shadeHex(base, 0.75), d: accent || shadeHex(base, -0.45) };
  let px = '';
  grid.forEach((row, y) => { for (let x = 0; x < 16; x++) { const ch = row[x]; if (ch !== '.') px += `<rect x="${x}" y="${y}" width="1" height="1" fill="${pal[ch]}"/>`; } });
  // rare and legendary cards get a little twinkle in the corner
  if (opts.rare || opts.legendary) px += [[14,0],[13,1],[14,1],[15,1],[14,2]].map(([x, y]) => `<rect class="twinkle" x="${x}" y="${y}" width="1" height="1" fill="${x === 14 && y === 1 ? '#fff' : '#ffe9a0'}"/>`).join('');
  return (_artCache[key] = `<svg class="sprite" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${px}</svg>`);
}

// A small version for lists (deck picker, deck builder)
function cardArtMini(c) {
  const { shape, base, accent } = cardArtSpec(c);
  return spriteSvg(shape, base, accent).replace('class="sprite"', 'class="sprite mini"');
}

// The art box at the top of a card: sprite plus a faint wash of the card's color behind it
function cardArtHtml(c) {
  const { shape, base, accent } = cardArtSpec(c);
  const r = c.rarity || 'common';
  const svg = spriteSvg(shape, base, accent, { rare: r === 'rare' || r === 'epic', legendary: r === 'legendary' });
  return `<div class="card-art" style="--art:${base}">${svg}</div>`;
}
