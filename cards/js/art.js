// Crystal malts shade with their number: Crystal 10 is golden, Crystal 120 is deep red-brown
function crystalTint(id) {
  const n = +id.replace('crystal', '');
  const t = Math.min(1, Math.max(0, (n - 10) / 110));
  const a = [0xe8, 0xb8, 0x60], b = [0x5a, 0x24, 0x14];
  return '#' + a.map((v, i) => Math.round(v + (b[i] - v) * t).toString(16).padStart(2, '0')).join('');
}
